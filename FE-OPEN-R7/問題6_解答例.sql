-- 問題6の解答例と検証

USE company_db;

-- =======================================
-- 元のクエリ（問題文）
-- =======================================
SELECT * FROM 商品 WHERE 仕入先ID IN ('M002', 'M004');

-- =======================================
-- ア: AND で結合
-- =======================================
SELECT * FROM 商品 WHERE 仕入先ID = 'M002' AND 仕入先ID = 'M004';
-- 結果: 0件（1つの商品が同時に2つの仕入先を持つことは不可能）

-- =======================================
-- イ: INTERSECT
-- =======================================
SELECT * FROM 商品 WHERE 仕入先ID = 'M002'
INTERSECT
SELECT * FROM 商品 WHERE 仕入先ID = 'M004';
-- 結果: 0件（共通部分は存在しない）
-- 注意: MySQLではINTERSECTが使えない場合があります

-- =======================================
-- ウ: OR で結合
-- =======================================
SELECT * FROM 商品 WHERE 仕入先ID = 'M002' OR 仕入先ID = 'M004';
-- 結果: 3件（M002とM004の商品が取得される）

-- =======================================
-- エ: BETWEEN
-- =======================================
SELECT * FROM 商品 WHERE 仕入先ID BETWEEN 'M002' AND 'M004';
-- 結果: 5件（文字列の範囲でM002〜M004が取得される）

-- =======================================
-- 正解の確認
-- =======================================
-- INと同じ結果になるのは「ウ」のORです

-- 元のクエリの結果
SELECT '元のクエリ(IN)' AS クエリ種類, * FROM 商品 WHERE 仕入先ID IN ('M002', 'M004');

-- ウの結果
SELECT 'ウ(OR)' AS クエリ種類, * FROM 商品 WHERE 仕入先ID = 'M002' OR 仕入先ID = 'M004';

-- 結果比較
SELECT 'IN を使用' AS 方法, COUNT(*) AS 件数 FROM 商品 WHERE 仕入先ID IN ('M002', 'M004')
UNION ALL
SELECT 'OR を使用' AS 方法, COUNT(*) AS 件数 FROM 商品 WHERE 仕入先ID = 'M002' OR 仕入先ID = 'M004';